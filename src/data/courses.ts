export const parsePrice = (price: string): number => {
  if (price.startsWith("$")) {
    const num = parseFloat(price.replace(/[^\d.]/g, ""));
    return isNaN(num) ? 0 : num * 5;
  }
  const cleaned = price.replace(/[^\d,]/g, "").replace(",", ".");
  const num = parseFloat(cleaned);
  return isNaN(num) ? 0 : num;
};

